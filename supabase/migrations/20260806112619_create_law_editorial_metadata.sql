create or replace function public.admin_criar_lei(
  p_ator_user_id uuid,p_slug text,p_titulo text,p_nome_curto text,p_descricao text,p_codigo text,p_categoria text,
  p_ativo boolean,p_ordem integer,p_thumbnail_url text,p_norma_originaria_referencia text,p_norma_originaria_data date,
  p_houve_alteracao_legislativa boolean,p_ultima_alteracao_referencia text,p_ultima_alteracao_data date,p_situacao_atualizacao text
) returns jsonb language plpgsql security definer set search_path=pg_catalog
as $function$
declare v_row public.leis;
begin
  perform public.admin_comercial_validar_contexto(p_ator_user_id);
  if p_slug is null or p_slug!~'^[a-z0-9]+(-[a-z0-9]+)*$' or p_titulo is null or pg_catalog.btrim(p_titulo)='' or p_ordem is null or p_ordem<0 then raise exception using errcode='22023',message='Dados da lei invalidos.'; end if;
  insert into public.leis(slug,titulo,nome_curto,descricao,codigo,categoria,ativo,ordem,thumbnail_url,norma_originaria_referencia,norma_originaria_data,houve_alteracao_legislativa,ultima_alteracao_referencia,ultima_alteracao_data,situacao_atualizacao)
