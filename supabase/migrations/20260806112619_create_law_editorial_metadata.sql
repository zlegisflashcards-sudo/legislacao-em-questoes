    visivel_catalogo=case when p_dados?'visivel_catalogo' then (p_dados->>'visivel_catalogo')::boolean else visivel_catalogo end,
    observacao_interna=case when p_dados?'observacao_interna' then nullif(p_dados->>'observacao_interna','') else observacao_interna end,
    data_publicacao=case when p_dados?'data_publicacao' then nullif(p_dados->>'data_publicacao','')::timestamptz else data_publicacao end
  where id=p_atualizacao_id returning * into v_after;
  if v_after.material_lei_id is not null and not exists(select 1 from public.materiais_leis where id=v_after.material_lei_id and lei_id=v_after.lei_id) then raise exception using errcode='22023',message='Material nao pertence a lei.'; end if;
  perform public.admin_comercial_auditar(p_ator_user_id,'atualizar','atualizacao_lei',p_atualizacao_id::text,pg_catalog.to_jsonb(v_before),pg_catalog.to_jsonb(v_after));
  return pg_catalog.to_jsonb(v_after);
end;
$function$;

create or replace function public.admin_ocultar_atualizacao_lei(p_ator_user_id uuid,p_atualizacao_id bigint)
returns jsonb language plpgsql security definer set search_path=pg_catalog
as $function$
declare v_before public.historico_atualizacoes_leis;v_after public.historico_atualizacoes_leis;
begin
  perform public.admin_comercial_validar_contexto(p_ator_user_id);
  select * into v_before from public.historico_atualizacoes_leis where id=p_atualizacao_id for update;
  if not found then raise exception using errcode='P0002',message='Atualizacao nao encontrada.'; end if;
  update public.historico_atualizacoes_leis set visivel_aluno=false,visivel_catalogo=false where id=p_atualizacao_id returning * into v_after;
  perform public.admin_comercial_auditar(p_ator_user_id,'ocultar','atualizacao_lei',p_atualizacao_id::text,pg_catalog.to_jsonb(v_before),pg_catalog.to_jsonb(v_after));
  return pg_catalog.to_jsonb(v_after);
end;
$function$;

create or replace function public.admin_publicar_nova_versao_material(
  p_ator_user_id uuid,p_material_lei_id bigint,p_nova_url_externa text,p_nova_versao text,p_nova_quantidade_itens integer,p_revisado_em date,p_publicado_em date,
  p_tipo_atualizacao text,p_importancia text,p_titulo text,p_descricao_resumida text,p_referencia_normativa text,p_data_referencia_normativa date,
  p_quantidade_questoes_adicionadas integer,p_quantidade_questoes_corrigidas integer,p_quantidade_flashcards_revisados integer,p_visivel_aluno boolean,p_visivel_catalogo boolean,p_observacao_interna text
) returns jsonb language plpgsql security definer set search_path=pg_catalog
as $function$
declare v_before public.materiais_leis;v_after public.materiais_leis;v_history jsonb;
begin
  perform public.admin_comercial_validar_contexto(p_ator_user_id);
  select * into v_before from public.materiais_leis where id=p_material_lei_id and tipo='flashcards' for update;
  if not found then raise exception using errcode='P0002',message='Material de flashcards nao encontrado.'; end if;
  if p_nova_url_externa is null or pg_catalog.btrim(p_nova_url_externa)='' or p_nova_versao is null or pg_catalog.btrim(p_nova_versao)='' or p_nova_quantidade_itens is null or p_nova_quantidade_itens<0 or p_revisado_em is null or p_publicado_em is null then raise exception using errcode='22023',message='Dados da nova versao invalidos.'; end if;
  update public.materiais_leis set url_externa=pg_catalog.btrim(p_nova_url_externa),versao_material=pg_catalog.btrim(p_nova_versao),quantidade_itens=p_nova_quantidade_itens,revisado_em=p_revisado_em,publicado_em=p_publicado_em,observacao_interna=p_observacao_interna,ativo=true where id=p_material_lei_id returning * into v_after;
  v_history:=public.admin_criar_atualizacao_lei(p_ator_user_id,v_before.lei_id,p_material_lei_id,p_tipo_atualizacao,p_importancia,p_titulo,p_descricao_resumida,p_referencia_normativa,p_data_referencia_normativa,v_before.versao_material,v_after.versao_material,v_before.quantidade_itens,v_after.quantidade_itens,p_quantidade_questoes_adicionadas,p_quantidade_questoes_corrigidas,p_quantidade_flashcards_revisados,p_visivel_aluno,p_visivel_catalogo,p_observacao_interna,pg_catalog.now());
  perform public.admin_comercial_auditar(p_ator_user_id,'publicar_versao','material_lei',p_material_lei_id::text,pg_catalog.to_jsonb(v_before),pg_catalog.to_jsonb(v_after),pg_catalog.jsonb_build_object('atualizacao_id',v_history->>'id','substitui_versao_anterior',true,'incremental',false));
  return pg_catalog.jsonb_build_object('material',pg_catalog.to_jsonb(v_after),'atualizacao',v_history);
end;
$function$;

