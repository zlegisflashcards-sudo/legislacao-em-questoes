create or replace view public.resumo_editorial_leis
with (security_barrier=true,security_invoker=true)
as
select
  lei.id as lei_id,
  lei.situacao_atualizacao,
  lei.norma_originaria_referencia,
  lei.norma_originaria_data,
  lei.houve_alteracao_legislativa,
  lei.ultima_alteracao_referencia,
  lei.ultima_alteracao_data,
  coalesce(pg_catalog.sum(material.quantidade_itens) filter (where material.ativo=true and material.tipo='flashcards' and material.quantidade_itens is not null),0)::bigint as quantidade_flashcards,
  (pg_catalog.array_agg(material.versao_material order by material.revisado_em desc nulls last,material.publicado_em desc nulls last,material.id desc) filter (where material.ativo=true and material.tipo='flashcards' and material.versao_material is not null))[1] as versao_material,
  pg_catalog.max(material.revisado_em) filter (where material.ativo=true and material.tipo='flashcards') as revisado_em
from public.leis as lei
left join public.materiais_leis as material on material.lei_id=lei.id
group by lei.id;

revoke all on public.resumo_editorial_leis from public,anon,authenticated,service_role;
grant select on public.resumo_editorial_leis to service_role;

