create or replace function public.definir_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $function$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$function$;

revoke all on function public.definir_updated_at() from public, anon, authenticated;
grant execute on function public.definir_updated_at() to service_role;

create table if not exists public.leis (
  id bigint generated by default as identity primary key,
  slug text not null,
  titulo text not null,
  nome_curto text,
  descricao text,
  codigo text,
  categoria text,
  ativo boolean not null default true,
  ordem integer not null default 0,
  thumbnail_url text,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now(),
  constraint leis_slug_normalizado_check check (
    slug = pg_catalog.lower(pg_catalog.btrim(slug))
    and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
  ),
  constraint leis_titulo_nao_vazio_check check (pg_catalog.btrim(titulo) <> ''),
  constraint leis_ordem_check check (ordem >= 0),
  constraint leis_slug_key unique (slug)
);

create index if not exists leis_ativo_ordem_idx
  on public.leis (ativo, ordem, id);
create index if not exists leis_categoria_idx
  on public.leis (categoria) where categoria is not null;

create table if not exists public.materiais_leis (
  id bigint generated by default as identity primary key,
  lei_id bigint not null,
  tipo text not null,
  titulo text not null,
  descricao text,
  provedor text not null default 'google_drive',
  url_externa text not null,
  acao text not null default 'abrir',
  ordem integer not null default 0,
  ativo boolean not null default true,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now(),
  constraint materiais_leis_lei_id_fkey
    foreign key (lei_id) references public.leis(id) on delete restrict,
  constraint materiais_leis_tipo_check check (
    tipo in ('flashcards', 'video', 'pdf', 'tutorial', 'audio', 'outro')
  ),
  constraint materiais_leis_provedor_check check (
    provedor in ('google_drive', 'youtube', 'externo', 'supabase_storage')
  ),
  constraint materiais_leis_acao_check check (
    acao in ('abrir', 'baixar', 'assistir')
  ),
  constraint materiais_leis_titulo_nao_vazio_check check (pg_catalog.btrim(titulo) <> ''),
  constraint materiais_leis_url_nao_vazia_check check (pg_catalog.btrim(url_externa) <> ''),
  constraint materiais_leis_ordem_check check (ordem >= 0)
