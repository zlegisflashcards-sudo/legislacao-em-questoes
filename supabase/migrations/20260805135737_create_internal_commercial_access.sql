-- public.produtos usa UUID como chave primaria no schema existente.
alter table public.produtos
  add column if not exists slug text,
  add column if not exists descricao text,
  add column if not exists hotmart_url text,
  add column if not exists observacao_administrativa text,
  add column if not exists ordem integer not null default 0,
  add column if not exists tipo_produto text not null default 'outro',
  add column if not exists updated_at timestamptz not null default pg_catalog.now();

alter table public.produtos
  alter column hotmart_product_id drop not null;

do $do$
begin
  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid = 'public.produtos'::pg_catalog.regclass
      and conname = 'produtos_slug_normalizado_check'
  ) then
    alter table public.produtos add constraint produtos_slug_normalizado_check
      check (
        slug is null
        or (
          slug = pg_catalog.lower(pg_catalog.btrim(slug))
          and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
        )
      );
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid = 'public.produtos'::pg_catalog.regclass
      and conname = 'produtos_tipo_produto_check'
  ) then
    alter table public.produtos add constraint produtos_tipo_produto_check
      check (tipo_produto in ('lei_avulsa', 'combo', 'edital', 'assinatura', 'outro'));
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid = 'public.produtos'::pg_catalog.regclass
      and conname = 'produtos_ordem_check'
  ) then
    alter table public.produtos add constraint produtos_ordem_check check (ordem >= 0);
  end if;
end;
$do$;

create unique index if not exists produtos_slug_unique_idx
  on public.produtos (slug) where slug is not null;
create index if not exists produtos_ativo_ordem_idx
  on public.produtos (ativo, ordem, id);
