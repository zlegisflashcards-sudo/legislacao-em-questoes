-- public.compras continua preservando os campos Hotmart antigos por compatibilidade.
alter table public.compras
  add column if not exists origem text not null default 'hotmart',
  add column if not exists identificador_externo text,
  add column if not exists observacao_administrativa text,
  add column if not exists administrador_user_id uuid,
  add column if not exists status_acesso text,
  add column if not exists adquirida_em timestamptz,
  add column if not exists cancelada_em timestamptz,
  add column if not exists reembolsada_em timestamptz,
  add column if not exists reativada_em timestamptz,
  add column if not exists updated_at timestamptz not null default pg_catalog.now();

alter table public.compras
  alter column hotmart_product_id drop not null;

update public.compras
set identificador_externo = hotmart_transaction_id
where identificador_externo is null
  and hotmart_transaction_id is not null;

update public.compras
set adquirida_em = comprada_em
where adquirida_em is null
  and comprada_em is not null;

update public.compras
set status_acesso = case
  when status in ('aprovada', 'manual') then 'ativo'
  when status in ('cancelada', 'chargeback') then 'cancelado'
  when status = 'reembolsada' then 'reembolsado'
  else null
end
where status_acesso is null;

do $do$
begin
  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid = 'public.compras'::pg_catalog.regclass
      and conname = 'compras_origem_check'
  ) then
    alter table public.compras add constraint compras_origem_check check (
      origem in ('hotmart', 'cortesia', 'amostra', 'premiacao', 'migracao', 'administrativo')
    );
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid = 'public.compras'::pg_catalog.regclass
      and conname = 'compras_status_acesso_check'
  ) then
    alter table public.compras add constraint compras_status_acesso_check check (
      status_acesso is null or status_acesso in ('ativo', 'cancelado', 'reembolsado')
    );
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid = 'public.compras'::pg_catalog.regclass
      and conname = 'compras_administrador_user_id_fkey'
  ) then
    alter table public.compras add constraint compras_administrador_user_id_fkey
      foreign key (administrador_user_id) references auth.users(id) on delete set null;
  end if;
end;
$do$;

