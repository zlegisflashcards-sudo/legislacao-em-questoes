-- Preserva o historico comercial quando um usuario Auth for excluido.
alter table public.alunos alter column user_id drop not null;

do $do$
declare
  tipo_exclusao "char";
begin
  select constraint_definition.confdeltype
  into tipo_exclusao
  from pg_catalog.pg_constraint as constraint_definition
  where constraint_definition.conrelid = 'public.alunos'::pg_catalog.regclass
    and constraint_definition.conname = 'alunos_user_id_fkey';

  if tipo_exclusao is distinct from 'n' then
    alter table public.alunos drop constraint if exists alunos_user_id_fkey;
    alter table public.alunos add constraint alunos_user_id_fkey
      foreign key (user_id) references auth.users(id) on delete set null;
  end if;
end;
$do$;

create or replace function public.criar_aluno_para_usuario()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $function$
begin
  insert into public.alunos (user_id, nome, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nome', new.raw_user_meta_data ->> 'name'),
    new.email
  )
  on conflict (user_id) do update
    set nome = coalesce(public.alunos.nome, excluded.nome),
        email = excluded.email,
        atualizado_em = pg_catalog.now();

  return new;
end;
$function$;

revoke all on function public.criar_aluno_para_usuario() from public, anon, authenticated;
grant execute on function public.criar_aluno_para_usuario() to service_role;

